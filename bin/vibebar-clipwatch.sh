#!/bin/bash
# Следит за буфером обмена и складывает каждое новое ⌘C в блокнот.
# Новый текст сначала ждёт VIBEBAR_PUSH_DELAY секунд: macrowhisper успевает пометить
# собственную диктовку, и она в блокнот не попадает.
set -uo pipefail
export PATH="/usr/bin:/bin:/usr/sbin:/opt/homebrew/bin:${PATH:-}"
export LANG="${LANG:-en_US.UTF-8}"; export LC_ALL="${LC_ALL:-$LANG}"
export __CF_USER_TEXT_ENCODING="${__CF_USER_TEXT_ENCODING:-0x$(printf '%X' "$(id -u)"):0x8000100:0x8000100}"

BIN="$(cd "$(dirname "$0")" && pwd)"; ROOT="$(dirname "$BIN")"
[ -f "$ROOT/config.env" ] && . "$ROOT/config.env"
BUF="${VIBEBAR_BUFFER:=$ROOT/clipboard.txt}"
MAX="${VIBEBAR_BUFFER_MAX:-15}"
LIMIT="${VIBEBAR_BUFFER_MAXLEN:-5000}"
INTERVAL="${VIBEBAR_WATCH_INTERVAL:-1}"
DELAY="${VIBEBAR_PUSH_DELAY:-5}"
LOGF="$ROOT/clip.log"
touch "$BUF"; chmod 600 "$BUF"

log() { printf '%s %s\n' "$(date '+%F %T')" "$1" >> "$LOGF"; tail -n 200 "$LOGF" > "$LOGF.t" && mv "$LOGF.t" "$LOGF"; }

LAST=""          # хеш последнего обработанного
PEND=""          # текст, ожидающий проверки
PEND_H=""
PEND_AT=0


while true; do
  sleep "$INTERVAL"

  INFO="$(osascript -e 'clipboard info' 2>/dev/null || true)"
  SKIP=0
  # По соглашению nspasteboard приложения метят содержимое:
  #   ConcealedType     — пароли, забирать нельзя
  #   TransientType     — временное
  #   AutoGeneratedType — положено программой, а не пользователем (кнопка «копировать» в приложении)
  # Раньше пропускались все три, из-за чего копия по кнопке в чате не попадала в блокнот.
  # Теперь по умолчанию пропускаем только пароли.
  for TY in ${VIBEBAR_SKIP_TYPES:-ConcealedType}; do
    case "$INFO" in *"$TY"*) SKIP=1; log "пропуск по типу $TY"; break ;; esac
  done

  if [ "$SKIP" = "0" ]; then
    T="$(pbpaste 2>/dev/null || true)"
    if [ -n "${T//[[:space:]]/}" ] && [ "${#T}" -le "$LIMIT" ]; then
      H="$(printf '%s' "$T" | shasum -a 256 | awk '{print $1}')"
      if [ "$H" != "$LAST" ] && [ "$H" != "$PEND_H" ]; then
        PEND="$T"; PEND_H="$H"; PEND_AT="$(date +%s)"
      fi
    fi
  fi

  # выдержка: даём macrowhisper время пометить диктовку
  if [ -n "$PEND_H" ] && [ "$(( $(date +%s) - PEND_AT ))" -ge "$DELAY" ]; then
    if printf '%s' "$PEND" | python3 "$BIN/_is_dictation.py"; then
      log "диктовка, пропуск: $(printf '%s' "$PEND" | tr '\n' ' ' | cut -c1-40)"
    else
      printf '%s' "$PEND" | BUF="$BUF" MAX="$MAX" VIBEBAR_CLEAN_TERMINAL="${VIBEBAR_CLEAN_TERMINAL:-1}" python3 "$BIN/_buf_push.py"
      log "в блокнот: $(printf '%s' "$PEND" | tr '\n' ' ' | cut -c1-40)"
    fi
    LAST="$PEND_H"; PEND=""; PEND_H=""; PEND_AT=0
  fi
done
